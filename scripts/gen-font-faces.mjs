// Writes @font-face rules that mirror, descriptor for descriptor, the CSS
// Google Fonts served v1 — same family names, weights, styles and
// unicode-range subsets — but with every src pointing at the byte-identical
// file shipped in a Fontsource package. Font matching (and so rendering)
// stays exactly as it was, with no request to Google.
//
//   node scripts/gen-font-faces.mjs
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { globSync } from 'node:fs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/141.0 Safari/537.36';

const TARGETS = [
  {
    out: 'src/styles/fonts.css',
    what: 'the main site (Newsreader, Geist, Geist Mono)',
    url: 'https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,300;0,6..72,400;0,6..72,500;1,6..72,300;1,6..72,400&family=Geist:wght@300;400;500;600&family=Geist+Mono:wght@400;500&display=swap',
  },
  {
    out: 'src/styles/fonts-project.css',
    what: 'the project deep-dives (Instrument Serif, Newsreader, IBM Plex Mono)',
    url: 'https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Newsreader:ital,opsz,wght@0,6..72,300;0,6..72,400;0,6..72,500;1,6..72,300;1,6..72,400&family=IBM+Plex+Mono:wght@400;500&display=swap',
  },
];

const PACKAGES = [
  '@fontsource-variable/newsreader',
  '@fontsource-variable/geist',
  '@fontsource-variable/geist-mono',
  '@fontsource/instrument-serif',
  '@fontsource/ibm-plex-mono',
];

const md5 = (buf) => createHash('md5').update(buf).digest('hex');
const byHash = new Map();
for (const pkg of PACKAGES) {
  // pnpm symlinks packages, which glob wildcards don't traverse — list each one.
  for (const f of globSync(`node_modules/${pkg}/files/*.woff2`, { cwd: root })) {
    byHash.set(md5(await readFile(join(root, f))), f.replace(/^node_modules\//, ''));
  }
}

for (const t of TARGETS) {
  const css = await (await fetch(t.url, { headers: { 'user-agent': UA } })).text();
  const cache = new Map();
  const rules = [];
  for (const [, subset, body] of css.matchAll(/\/\* (\S+) \*\/\s*@font-face \{([^}]*)\}/g)) {
    const src = body.match(/url\((\S+?)\)/)[1];
    if (!cache.has(src)) cache.set(src, md5(Buffer.from(await (await fetch(src)).arrayBuffer())));
    const pkgFile = byHash.get(cache.get(src));
    if (!pkgFile) throw new Error(`No Fontsource file matches ${src} (${subset})`);
    const decl = (k) => body.match(new RegExp(`${k}: ([^;]+);`))[1];
    rules.push(
      `/* ${subset} */\n@font-face{font-family:${decl('font-family')};font-style:${decl('font-style')};font-weight:${decl('font-weight')};font-display:swap;` +
        `src:url('${pkgFile}') format('woff2');unicode-range:${decl('unicode-range')}}`,
    );
  }
  const header = `/* Generated by scripts/gen-font-faces.mjs — do not edit.\n   Self-hosted faces for ${t.what}: Google Fonts' descriptors, Fontsource's\n   byte-identical files. */\n`;
  await writeFile(join(root, t.out), header + rules.join('\n') + '\n');
  console.log(`${t.out}: ${rules.length} faces`);
}
